
'use server';
/**
 * @fileOverview A Genkit flow for logging spiritual or social rites.
 *
 * - logRite - A function that processes and prepares rite data for logging.
 * - LogRiteInput - The input type for the logRite function.
 * - LogRiteOutput - The return type for the logRite function.
 */

import {ai} from '@/ai/genkit';
import {z} from 'genkit';

// Based on rites.schema.json
export const LogRiteInputSchema = z.object({
  memberId: z.string().min(1, 'Member ID is required.'),
  type: z.string().min(3, 'Rite type is required (e.g., marriage, birth, funeral).'),
  date: z.string().refine((val) => !isNaN(Date.parse(val)), {
    message: "Date must be a valid date string.",
  }),
  officiant: z.string().min(1, 'Officiant ID is required.'),
  audioArchiveUrl: z.string().url().optional().describe('Optional URL to an audio recording of the rite.'),
  notes: z.string().optional().describe('Optional notes or details about the rite.'),
  blessingScripture: z.string().optional().describe('Optional scriptural reference for a blessing.'),
  // clanId might be useful for querying/security rules, passed by the calling API
  clanId: z.string().min(1, 'Clan ID is required for context.').optional(),
});
export type LogRiteInput = z.infer<typeof LogRiteInputSchema>;

export const LogRiteOutputSchema = z.object({
  riteId: z.string().describe('The ID of the logged rite (usually generated by Firestore).'),
  loggedAt: z.string().describe('Timestamp of when the rite was logged.'),
  summary: z.string().describe('A brief summary of the logged rite.'),
  processedInput: LogRiteInputSchema.extend({
    // Add any fields processed by the AI/flow if needed
    isoDate: z.string().describe("Date of the rite in ISO format for consistent storage.")
  })
});
export type LogRiteOutput = z.infer<typeof LogRiteOutputSchema>;


export async function logRite(input: LogRiteInput): Promise<LogRiteOutputSchema> {
  // This flow primarily structures data. AI could be used here to:
  // - Suggest blessing scriptures based on rite type and notes.
  // - Generate a more detailed summary.
  // - Validate cultural appropriateness if more context is provided.
  return logRiteFlow(input);
}

const riteLoggingPrompt = ai.definePrompt({
  name: 'riteLoggingPrompt',
  input: {schema: LogRiteInputSchema},
  output: {schema: z.object({ summary: z.string(), isoDate: z.string() }) },
  prompt: `
    A new rite is being logged with the following details:
    Type: {{{type}}}
    Member ID: {{{memberId}}}
    Date: {{{date}}}
    Officiant: {{{officiant}}}
    {{#if notes}}Notes: {{{notes}}}{{/if}}
    {{#if blessingScripture}}Blessing Scripture: {{{blessingScripture}}}{{/if}}

    Based on these details, provide a concise one-sentence summary for this rite.
    Also, convert the provided date "{{{date}}}" into ISO 8601 format.
  `,
});

const logRiteFlow = ai.defineFlow(
  {
    name: 'logRiteFlow',
    inputSchema: LogRiteInputSchema,
    outputSchema: LogRiteOutputSchema, // The flow itself doesn't return riteId, that's from DB
  },
  async (input: LogRiteInput) => {
    const {output: promptOutput} = await riteLoggingPrompt(input);

    if (!promptOutput) {
      throw new Error("Failed to get a response from the rite logging prompt.");
    }
    
    // The riteId will be generated by Firestore when the document is created.
    // The loggedAt timestamp will also be set by the server/API route.
    return {
      riteId: '', // To be filled by the caller after DB insert
      loggedAt: new Date().toISOString(), // Placeholder, actual value set by API
      summary: promptOutput.summary,
      processedInput: {
        ...input,
        isoDate: promptOutput.isoDate,
      }
    };
  }
);
